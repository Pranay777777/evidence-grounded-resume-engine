"""Collect raw generations for the golden set.

Deliberately **ungated**: every bullet the model writes is kept, including
the ones the grounding checks would drop. The golden set exists to measure
the gate, so it must contain what the gate is meant to catch.

Requires a pinned model. `openrouter/free` picks a model at random per
request, and a golden set generated by an unknown mixture of models cannot
be regenerated or compared (ADR-007).

Free models are rate limited upstream, so collection is incremental: each
job's bullets are saved as soon as they arrive, a provider error skips that
job rather than ending the run, and jobs a model has already answered are
skipped on the next run — a rerun spends quota only on what is missing.
"""

from __future__ import annotations

from collections.abc import Callable
from dataclasses import dataclass, field
from pathlib import Path

from sqlalchemy import create_engine
from sqlalchemy.orm import Session

from grounded.evals.golden import GoldenItem, JobSet, item_id
from grounded.evidence.models import Base, Evidence
from grounded.evidence.store import load, read_file
from grounded.generation.generate import ChatClient, GenerationError, generate
from grounded.generation.llm import FREE_ROUTER, LLMError
from grounded.retrieval.embedding import Embedder
from grounded.retrieval.index import embed_pending
from grounded.retrieval.search import search
from grounded.verification.grounding import premise

MAX_CONSECUTIVE_FAILURES = 3


class PinRequiredError(ValueError):
    pass


def same_model(a: str, b: str) -> bool:
    """Providers echo ids with or without the `:free` variant suffix."""
    return a.split(":", 1)[0] == b.split(":", 1)[0]


@dataclass
class Collection:
    items: list[GoldenItem] = field(default_factory=list)
    done: list[str] = field(default_factory=list)
    failed: list[str] = field(default_factory=list)
    skipped: list[str] = field(default_factory=list)
    stopped: bool = False
    """True if the run gave up after consecutive provider errors."""


def collect(
    corpus: Path,
    jobs: JobSet,
    client: ChatClient,
    embedder: Embedder,
    k: int = 8,
    skip: frozenset[str] = frozenset(),
    save: Callable[[list[GoldenItem]], None] = lambda items: None,
    progress: Callable[[str], None] = print,
) -> Collection:
    if client.model == FREE_ROUTER:
        raise PinRequiredError(
            f"the golden set needs a pinned model, not '{FREE_ROUTER}' — pick one from "
            "`python -m grounded.generation models` and pass --model"
        )
    engine = create_engine("sqlite://")
    Base.metadata.create_all(engine)
    result = Collection()
    streak = 0
    with Session(engine) as session:
        load(session, read_file(corpus))
        embed_pending(session, embedder)
        for job in jobs.jds:
            if job.id in skip:
                result.skipped.append(job.id)
                continue
            if streak >= MAX_CONSECUTIVE_FAILURES:
                result.stopped = True
                result.failed.append(job.id)
                continue
            hits = search(session, job.text, embedder, k=k)
            records = [session.get(Evidence, h.evidence_id) for h in hits]
            given = {r.id: r for r in records if r is not None}
            try:
                generation = generate(client, job.text, list(given.values()))
            except LLMError as exc:
                streak += 1
                result.failed.append(job.id)
                progress(f"  {job.id}: provider error ({exc})")
                continue
            except GenerationError as exc:
                streak = 0
                result.failed.append(job.id)
                progress(f"  {job.id}: no draft ({exc})")
                continue
            streak = 0
            batch = [
                GoldenItem(
                    id=item_id(job.id, generation.model, bullet.text),
                    jd_id=job.id,
                    model=generation.model,
                    prompt_version=generation.prompt_version,
                    text=bullet.text,
                    evidence_ids=list(bullet.evidence_ids),
                    premise=premise([given[i] for i in bullet.evidence_ids if i in given]),
                    unknown_ids=[i for i in bullet.evidence_ids if i not in given],
                )
                for bullet in generation.draft.bullets
            ]
            save(batch)
            result.items.extend(batch)
            result.done.append(job.id)
            progress(f"  {job.id}: {len(batch)} bullet(s) from {generation.model}")
    return result
